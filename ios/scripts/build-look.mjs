#!/usr/bin/env node
// Builds the phone's look resources from desktop's Studio plugin source:
//
//   iOS/Look/Resources/look.js  desktop's scene engine, the six scene drivers and
//                               the presence forms and sandbox, for the app's
//                               sandboxed WKWebView (Look/web/runtime.ts)
//   Shared/Look/looks.json      every theme's resolved colors and glass, from
//                               desktop's resolveLook (Look/web/export.ts)
//
//   node scripts/build-look.mjs          write both
//   node scripts/build-look.mjs --check  fail if either is out of date
//
// It needs plugins/node_modules (cd plugins && pnpm install). The outputs are
// committed, so an Xcode build never needs Node.
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ios = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repo = resolve(ios, "..");
const tsx = join(repo, "plugins/node_modules/tsx/package.json");
if (!existsSync(tsx)) {
  console.error("build-look: plugins/node_modules is missing; run `pnpm install` in plugins/ first.");
  process.exit(2);
}
const esbuild = createRequire(realpathSync(tsx))("esbuild");
const check = process.argv.includes("--check");
const web = join(ios, "Look/web");
const outputs = { js: join(ios, "iOS/Look/Resources/look.js"), json: join(ios, "Shared/Look/looks.json") };

const reactStub = {
  name: "react-stub",
  setup(build) {
    build.onResolve({ filter: /^react$/ }, () => ({ path: join(web, "react-stub.ts") }));
  },
};

const header = "// Generated by ios/scripts/build-look.mjs from plugins/packages/bb-studio/src/{theme,presence}. Do not edit.\n";
const bundle = await esbuild.build({
  entryPoints: [join(web, "runtime.ts")],
  bundle: true, write: false, format: "iife", platform: "browser", target: "safari18", minify: true,
  legalComments: "none", charset: "utf8", plugins: [reactStub], logLevel: "warning",
});
const js = header + bundle.outputFiles[0].text;

const scratch = mkdtempSync(join(tmpdir(), "build-look-"));
let json;
try {
  const runner = join(scratch, "export.mjs");
  await esbuild.build({ entryPoints: [join(web, "export.ts")], bundle: true, outfile: runner, format: "esm", platform: "node", target: "node20", plugins: [reactStub], logLevel: "warning" });
  const out = join(scratch, "looks.json");
  execFileSync(process.execPath, [runner, out], { stdio: "inherit" });
  json = readFileSync(out, "utf8");
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

const stale = [];
for (const [path, text] of [[outputs.js, js], [outputs.json, json]]) {
  const now = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (now === text) continue;
  if (check) stale.push(path.slice(ios.length + 1));
  else writeFileSync(path, text);
}
if (check && stale.length) {
  console.error(`build-look: out of date: ${stale.join(", ")}. Run node ios/scripts/build-look.mjs.`);
  process.exit(1);
}
console.log(check ? "build-look: up to date" : `build-look: wrote look.js (${Math.round(js.length / 1024)} KB) and looks.json (${Math.round(json.length / 1024)} KB)`);
