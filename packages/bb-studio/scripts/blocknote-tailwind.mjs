// BlockNote's shadcn UI is styled with Tailwind classes, but `bb plugin build`
// only generates classes it finds in the plugin's own files, not in
// node_modules. This copies the class strings from BlockNote's bundle into
// blocknote-tailwind.txt so the build generates them. Run it after upgrading
// @blocknote/shadcn: `pnpm tailwind:blocknote`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "package.json"));
const bundle = readFileSync(require.resolve("@blocknote/shadcn").replace(/\.cjs$/, ".js"), "utf8");
const classes = new Set();
for (const [, double, single, template] of bundle.matchAll(/"((?:[^"\\\n]|\\.)*)"|'((?:[^'\\\n]|\\.)*)'|`([^`]*)`/g)) {
  for (const token of (double ?? single ?? template ?? "").split(/\s+/)) {
    // Utility-like tokens only: skips prose, URLs and JS identifiers.
    if (/^[!-]?[a-z@*[][\w\-:/.[\]()%&>*=,'#!~]*$/.test(token)) classes.add(token);
  }
}
const header = "# Generated by scripts/blocknote-tailwind.mjs from @blocknote/shadcn. Don't edit.\n";
writeFileSync(join(root, "blocknote-tailwind.txt"), header + [...classes].sort().join("\n") + "\n");
console.log(`blocknote-tailwind.txt: ${classes.size} classes`);
