#!/usr/bin/env node
// Builds the mini apps' shelf (shelf/*.js): the libraries Studio ships for
// mini apps, as classic scripts their sandboxed frame loads from Studio.
//
// A sandboxed frame has an opaque origin, so ES module imports from Studio
// would be cross-origin requests BB's local auth refuses. Classic scripts
// aren't, so each lib is an IIFE that registers its modules in
// `globalThis.__miniShelf`, and a mini app's compiled `require()` reads them
// (src/minis/shelf/runtime.ts). Libs that need another (Kit needs React)
// read it from the registry instead of bundling a second copy.
//
// The output is committed: BB installs plugins with `npm install --omit=dev`,
// so the shelf can't be built at install time. Run after changing a lib or
// its version: `node scripts/build-shelf.mjs` (in packages/bb-studio).
import { build } from "esbuild";
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "shelf");
const require = createRequire(join(root, "package.json"));

/** id → modules it registers, from what source, and which registered modules it reads. */
const LIBS = [
  { id: "runtime-1", entry: "src/minis/shelf/runtime.ts", modules: {} },
  {
    id: "react-19",
    modules: { react: "react", "react/jsx-runtime": "react/jsx-runtime", "react-dom": "react-dom", "react-dom/client": "react-dom/client" },
  },
  { id: "kit-1", modules: { "@studio/kit": "./src/minis/shelf/kit.tsx" }, external: ["react", "react/jsx-runtime", "react-dom", "react-dom/client"] },
  {
    id: "charts-1",
    modules: { "@studio/kit/charts": "./src/minis/shelf/charts.tsx", recharts: "recharts" },
    external: ["react", "react/jsx-runtime", "react-dom", "react-dom/client"],
  },
  { id: "icons-1", modules: { "lucide-react": "lucide-react" }, external: ["react", "react/jsx-runtime", "react-dom", "react-dom/client"] },
  { id: "markdown-1", modules: { marked: "marked" } },
  { id: "dates-4", modules: { "date-fns": "date-fns" } },
];

/** Imports of modules another lib registers become reads from the registry. */
function registryPlugin(names) {
  const filter = new RegExp(`^(${names.map((name) => name.replace(/[/\-]/g, "\\$&")).join("|")})$`);
  return {
    name: "mini-shelf-registry",
    setup(b) {
      b.onResolve({ filter }, (args) => ({ path: args.path, namespace: "mini-shelf" }));
      b.onLoad({ filter: /.*/, namespace: "mini-shelf" }, (args) => ({ contents: `module.exports = globalThis.__miniShelf[${JSON.stringify(args.path)}];`, loader: "js" }));
    },
  };
}

/** Kit's Icon comes from BB in Studio; in a frame, from Lucide. */
const sdkShim = {
  name: "sdk-app-shim",
  setup(b) {
    b.onResolve({ filter: /^@get-bb\/plugin-sdk\/app$/ }, () => ({ path: join(root, "src/minis/shelf/icon-shim.tsx") }));
  },
};

function registerSource(modules) {
  const lines = [
    "const shelf = (globalThis.__miniShelf ||= {});",
    // CommonJS builds (React) come in with `default`; ESM ones get it as the namespace.
    "const wrap = (ns) => Object.assign(Object.create(null), ns, { __esModule: true, default: ns.default ?? ns });",
  ];
  Object.entries(modules).forEach(([name, source], index) => {
    lines.unshift(`import * as m${index} from ${JSON.stringify(source)};`);
    lines.push(`shelf[${JSON.stringify(name)}] = wrap(m${index});`);
  });
  return lines.join("\n");
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

for (const lib of LIBS) {
  const options = {
    bundle: true,
    format: "iife",
    minify: true,
    target: "es2022",
    jsx: "automatic",
    legalComments: "eof",
    define: { "process.env.NODE_ENV": '"production"' },
    outfile: join(out, `${lib.id}.js`),
    plugins: [...(lib.external ? [registryPlugin(lib.external)] : []), sdkShim],
    logLevel: "warning",
    absWorkingDir: root,
  };
  if (lib.entry) await build({ ...options, entryPoints: [join(root, lib.entry)] });
  else await build({ ...options, stdin: { contents: registerSource(lib.modules), resolveDir: root, sourcefile: `${lib.id}.js`, loader: "tsx" } });
}

copyFileSync(require.resolve("@tailwindcss/browser"), join(out, "tailwind-4.js"));

const files = readdirSync(out).filter((name) => name.endsWith(".js")).sort();
writeFileSync(join(out, "README.md"), `# Mini app shelf\n\nGenerated by \`node scripts/build-shelf.mjs\`; don't edit. See src/minis/shared.ts (SHELF).\n\n${files.map((name) => `- ${name}`).join("\n")}\n`);
console.log(`Built ${files.length} shelf files in ${out}`);
