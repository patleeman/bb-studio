export function withToolLabel<Tool extends { name: string; presentation?: { label?: unknown; [key: string]: unknown } }>(tool: Tool): Tool {
  const labels = TOOL_LABELS[tool.name];
  if (!labels || tool.presentation?.label) return tool;
  return { ...tool, presentation: { ...tool.presentation, label: { pending: labels[0], completed: labels[1] } } };
}
