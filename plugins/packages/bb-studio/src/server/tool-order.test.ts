it("pins the exact registered agent tool order so prompt caches stay stable", async () => {
  const host = createFakePluginHost({
    pluginId: "studio",
    sdk: {
      threads: { list: async () => [] },
      projects: { list: async () => [] },
      providers: { catalog: async () => [] },
    },
  } as never);
  await plugin(host.bb);
  try {
    const names = (host.harness.registrations as unknown as { agentTools: { name: string }[] }).agentTools.map((tool) => tool.name);
    expect(names).toEqual(EXPECTED_TOOL_ORDER);
  } finally {
    await host.harness.lifecycle.dispose();
  }
});
